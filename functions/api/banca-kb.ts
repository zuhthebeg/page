const clauseMap = new Map(CLAUSES.map((c) => [c.id, c]));
const precMap = new Map(PRECEDENTS.map((p) => [p.id, p]));

export const getClause = (id: string) => clauseMap.get(id) || null;
export const getPrecedent = (id: string) => precMap.get(id) || null;

// 위험점수 = 건수 × (1 + 설명누락률). 성공률 = overturned / denials.
export function clauseStats() {
  return CLAIM_HISTORY.map((h) => {
    const c = clauseMap.get(h.clause_id);
    return {
      clause_id: h.clause_id,
      ref: c?.ref || h.clause_id,
      title: c?.title || "",
      product: c?.product || "",
      denials: h.denials,
      missing_rate: h.missing_rate,
      success_rate: Math.round((h.overturned / h.denials) * 100) / 100,
      risk_score: Math.round(h.denials * (1 + h.missing_rate)),
    };
  }).sort((a, b) => b.risk_score - a.risk_score);
}

export function promotedClauses(n = 4) {
  return clauseStats().slice(0, n);
}

export function statFor(clauseId: string) {
  return clauseStats().find((s) => s.clause_id === clauseId) || null;
}

// ── 프롬프트 주입용 ──
export function kbClausesPrompt(): string {
  return CLAUSES.map((c) => `[${c.id}] ${c.ref} — ${c.title} (${c.product})\n${c.text}`).join("\n\n");
}

export function kbPrecedentsPrompt(): string {
  return PRECEDENTS.map(
    (p) => `[${p.id}] ${p.no} — ${p.title} (관련 조항: ${p.clause_ids.join(",")})\n사실관계: ${p.facts}\n결정: ${p.decision}`,
  ).join("\n\n");
}

export function opsAlertPrompt(): string {
  const top = promotedClauses(4);
  return top
    .map(
      (s) =>
        `[${s.clause_id}] ${s.ref}(${s.title}) — 부지급 ${s.denials}건, 설명누락률 ${Math.round(s.missing_rate * 100)}%, 위험점수 ${s.risk_score} → 판매 필수 설명으로 자동 승격됨`,
    )
    .join("\n");
}
